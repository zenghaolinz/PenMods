"""Regenerate embedded Qt 5 resource arrays on Windows or Linux."""

from __future__ import annotations

import argparse
import re
import subprocess
import tempfile
from pathlib import Path


def generate(model: Path, rcc: str = "rcc") -> None:
    model = model.resolve()
    manifest = model / "resource.qrc"
    # Keep the existing manifest: it is the explicit list of shipped resources.
    with tempfile.TemporaryDirectory() as directory:
        output = Path(directory) / "qrc_qml.cpp"
        subprocess.run([rcc, "--format-version", "3", "-name", "qml",
                        str(manifest), "-o", str(output)], check=True)
        code = output.read_text(encoding="utf-8")
    arrays = re.findall(
        r"static const unsigned char qt_resource_(?:data|name|struct)\[\] = \{.*?\n\};",
        code, re.DOTALL,
    )
    if len(arrays) != 3:
        raise ValueError("rcc did not emit the three expected resource arrays")
    header = "// Generated by scripts/gen_qt_res.py using Qt rcc. Do not edit.\n\n"
    body = "\n\n".join(arrays).replace(model.as_posix() + "/", "")
    body = "\n".join(line.rstrip() for line in body.splitlines())
    (model / "qrc_qml.h").write_text(header + body + "\n", encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model", type=Path)
    parser.add_argument("--rcc", default="rcc")
    args = parser.parse_args()
    generate(args.model, args.rcc)
